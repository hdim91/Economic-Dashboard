#!/bin/bash
# ============================================================================
# run_pipeline.sh — 통합 파이프라인 진입점
# 고용동향 → 금융동향 순차 실행
# ============================================================================
set -e

echo "============================================================"
echo "[pipeline] 통합 파이프라인 시작"
echo "============================================================"

# ── Step 1: 고용동향 수집·적재 ──────────────────────────────────────────────
echo ""
echo "[pipeline] Step 1: 고용동향 파이프라인"
echo "------------------------------------------------------------"
cd /app/employment

# 고용동향은 R 분석 없이 수집·BQ 적재까지만 실행
# (R 분석은 report-job에서 담당)
ANALYSIS_ENABLED=false python main.py

# ── Step 2: 금융동향 수집·적재 ──────────────────────────────────────────────
echo ""
echo "[pipeline] Step 2: 금융동향 파이프라인"
echo "------------------------------------------------------------"
cd /app/finance

# 금융동향도 R 분석 없이 수집·BQ 적재까지만
ANALYSIS_ENABLED=false python finance_main.py

echo ""
echo "============================================================"
echo "[pipeline] 통합 파이프라인 완료"
echo "============================================================"
